#!/usr/bin/env python3
"""Erzeugt aus den Katalog-Sätzen (katalog.py) die Dart-Dateien lib/features/lessons/data/sheets/<id>_sheet.dart.

Aufruf: gen_dart.py <lib/features/lessons/data/sheets> [satz]
Danach `dart format` auf der Maschine mit Flutter.
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from katalog import select  # noqa: E402
from sheetlang import line_to_dart  # noqa: E402


def camel(ident: str) -> str:
    head, *rest = ident.split('_')
    return head + ''.join(p.capitalize() for p in rest)


def dart_str(s: str) -> str:
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def render(sheet, step: str, source: str) -> str:
    from sheetlang import kit_line_to_dart, note_to_dart, voice_to_dart
    c = camel(sheet.id)
    lines = sheet.parsed()
    pat = sheet.pattern_line()
    if sheet.kit:
        body = '\n'.join(kit_line_to_dart(ln) for ln in lines)
        voices = '\n'.join(voice_to_dart(t, '') for t in pat.tracks)
        extra_import = "import '../../../coaching/midi/kit_instrument.dart';\n"
        pattern_voices = (f'\n/// {sheet.name}: the PATTERN bar, every voice (Brief B.1).\n'
                          f'final List<Voice> {c}PatternVoices = [\n{voices}\n];\n')
        pattern_block = (f'/// {sheet.name}: the first voice of the PATTERN bar — see {c}PatternVoices.\n'
                         f'final List<StrokeBeat> {c}Pattern = {c}PatternVoices.first.beats;\n')
    else:
        body = '\n'.join(line_to_dart(ln) for ln in lines)
        pattern = '\n'.join('  ' + note_to_dart(n) + ',' for n in pat.notes)
        extra_import = ''
        pattern_voices = ''
        pattern_block = (f'/// {sheet.name}: the plain pattern, one bar — the PATTERN box on the info\n'
                         f'/// page and the exercise\'s `sticking`.\n'
                         f'final List<StrokeBeat> {c}Pattern = [\n{pattern}\n];\n')
    lesson = '\n'.join(
        f'  TechniqueSection(\n    title: {dart_str(k)},\n    body: {dart_str(v)},\n  ),'
        for k, v in sheet.lesson.items())
    form = ('8 lines of two bars' if sheet.line_bars == 2
            else '8 lines of four bars (three bars of time, one bar of fill)' if sheet.fill_bar
            else '8 lines of four bars, harder line by line')
    return f'''// GENERATED by tool/katalog/gen_dart.py from tool/katalog/{source} —
// edit the Python source, not this file. Katalog Schritt {step} ({sheet.name}).
{extra_import}import '../../models/rudiment.dart';
import '../etude_dsl.dart';
{pattern_voices}
{pattern_block}
/// {sheet.name}: {form}, composed
/// by the rule "as varied and groovy as possible" (Uli, 30.09.).
final List<ExerciseLine> {c}Sheet = [
{body}
];

/// Lesson sections for the info page — never shown on the practice screen.
const List<TechniqueSection> {c}Lesson = [
{lesson}
];
'''


def main(out_dir: pathlib.Path, set_key: str | None) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for st in select(set_key):
        for s in st.sheets:
            path = out_dir / f'{s.id}_sheet.dart'
            path.write_text(render(s, st.step, f'{st.key}.py'))
            print('wrote', path.name)


if __name__ == '__main__':
    main(pathlib.Path(sys.argv[1]), sys.argv[2] if len(sys.argv) > 2 else None)
