#!/usr/bin/env python3
"""Erzeugt tool/stimme/saetze_raum.py — `RAUM`, Clip-ID `h_<id>` → gesprochene Kurzfassung des
„How“-Abschnitts der Hände-Technik-Blätter (technik.VOICE_HOW).

Aufruf: gen_raum_voice.py <repo_root>
Die Ausgabe hängt nur von den Daten ab: zweimal laufen = gleiche Bytes.
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

PY_OUT = 'tool/stimme/saetze_raum.py'
HEADER = 'GENERATED by tool/katalog/gen_raum_voice.py from tool/katalog/technik.py — do not edit.'
MAX_WORDS = 40


def clip_id(sheet_id: str) -> str:
    return f'h_{sheet_id}'


def check(sheets, voice: dict[str, str]) -> None:
    ids = [s.id for s in sheets]
    if sorted(voice) != sorted(ids):
        raise ValueError(f'VOICE_HOW ids differ from sheets: {sorted(set(voice) ^ set(ids))}')
    for sid, text in voice.items():
        if len(text.split()) > MAX_WORDS:
            raise ValueError(f'{sid}: voice text has {len(text.split())} words (max {MAX_WORDS})')
        if not text.isascii():
            raise ValueError(f'{sid}: voice text must be ASCII')


def render_py(sheets, voice: dict[str, str]) -> str:
    rows = ''.join(f'    {clip_id(s.id)!r}: {voice[s.id]!r},\n' for s in sheets)
    return f'''# {HEADER}
"""Spoken short version of the "How" lesson of each hand-technique sheet: clip id -> English text."""

RAUM = {{
{rows}}}
'''


def generate(root: pathlib.Path, sheets, voice: dict[str, str]) -> pathlib.Path:
    check(sheets, voice)
    path = root / PY_OUT
    path.write_text(render_py(sheets, voice), encoding='utf-8')
    return path


def main(root: pathlib.Path) -> None:
    from technik import SHEETS, VOICE_HOW
    print('wrote', generate(root, SHEETS, VOICE_HOW).relative_to(root))


if __name__ == '__main__':
    main(pathlib.Path(sys.argv[1]))
