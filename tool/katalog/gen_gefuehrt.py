#!/usr/bin/env python3
"""Erzeugt aus den geführten Übungen (gefuehrt.py) zwei Dateien:

  lib/features/guided/data/guided_catalog.dart  — `guidedCatalog`, die Übungen der App
  tool/stimme/saetze_gefuehrt.py                — `GEFUEHRT`, Clip-ID → englischer Satz

Aufruf: gen_gefuehrt.py <repo_root>
Danach `dart format lib/features/guided/data/guided_catalog.dart` auf der Maschine mit Flutter.
Die Ausgabe hängt nur von den Daten ab (keine Zeitstempel): zweimal laufen = gleiche Bytes.
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from gefuehrt_blatt import GuidedSheet, check_catalog  # noqa: E402
from sheetlang import KitLine, kit_line_to_dart, line_to_dart  # noqa: E402

DART_OUT = 'lib/features/guided/data/guided_catalog.dart'
PY_OUT = 'tool/stimme/saetze_gefuehrt.py'
HEADER = 'GENERATED by tool/katalog/gen_gefuehrt.py from tool/katalog/gefuehrt.py — do not edit.'


def dart_str(s: str) -> str:
    """Dart-String in einfachen Anführungszeichen (Lint prefer_single_quotes)."""
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def _line(ln, indent: str) -> str:
    """Dart-Ausdruck einer Zeile (ohne Komma am Ende)."""
    text = kit_line_to_dart(ln, indent) if isinstance(ln, KitLine) else line_to_dart(ln, indent)
    return text.strip().rstrip(',')


def _section(kind: str, line: str, bars: int, *, text: str | None = None,
             clip: str | None = None, after: str | None = None) -> str:
    args = [f'kind: SectionKind.{kind}', f'line: {line}', f'bars: {bars}']
    if text is not None:
        args.append(f'textEn: {dart_str(text)}')
    if clip is not None:
        args.append(f'speechClipId: {dart_str(clip)}')
    if after is not None:
        args.append(f'afterClipId: {dart_str(after)}')
    return '      GuidedSection(\n' + ''.join(f'        {a},\n' for a in args) + '      ),'


def render_exercise(s: GuidedSheet) -> str:
    groove, variations = s.parsed()
    g = _line(groove, '        ')
    sections = [_section('intro', 'const ExerciseLine([])', 0)]
    for n, (v, ln) in enumerate(zip(s.variations, variations), 1):
        sections.append(_section('groove', g, s.groove_bars))
        sections.append(_section('variation', _line(ln, '        '), s.variation_bars,
                                 text=v.text, clip=s.clip_id(n), after=v.after))
    sections.append(_section('groove', g, s.groove_bars))
    sections.append(_section('outro', g, 1))
    body = '\n'.join(sections)
    return f'''  GuidedExercise(
    id: {dart_str(s.id)},
    name: {dart_str(s.name)},
    description: {dart_str(s.description)},
    package: GuidedPackage.{s.package},
    difficulty: Difficulty.{s.difficulty},
    defaultBpm: {s.default_bpm},
    minBpm: {s.min_bpm},
    maxBpm: {s.max_bpm},
    gridUnit: NoteGrid.{s.grid},
    sections: [
{body}
    ],
  ),'''


def render_dart(sheets: list[GuidedSheet]) -> str:
    kit = any(s.package == 'kit' for s in sheets)
    imports = ("import '../../coaching/midi/kit_instrument.dart';\n" if kit else '')
    exercises = '\n'.join(render_exercise(s) for s in sheets)
    return f'''// {HEADER}
{imports}import '../../lessons/data/etude_dsl.dart';
import '../../lessons/models/rudiment.dart';
import '../models/guided_exercise.dart';

/// The guided exercises of the app: groove + variations with spoken
/// English explanations (Plan 2 Katalog).
final List<GuidedExercise> guidedCatalog = [
{exercises}
];
'''


def render_py(sheets: list[GuidedSheet]) -> str:
    rows = ''.join(f'    {s.clip_id(n)!r}: {v.text!r},\n'
                   for s in sheets for n, v in enumerate(s.variations, 1))
    return f'''# {HEADER}
"""Explanations of the guided exercises: clip id -> English text (spoken by Piper)."""

GEFUEHRT = {{
{rows}}}
'''


def generate(root: pathlib.Path, sheets: list[GuidedSheet]) -> list[pathlib.Path]:
    check_catalog(sheets)
    out = []
    for rel, text in ((DART_OUT, render_dart(sheets)), (PY_OUT, render_py(sheets))):
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
        out.append(path)
    return out


def main(root: pathlib.Path) -> None:
    from gefuehrt import SHEETS
    for path in generate(root, SHEETS):
        print('wrote', path.relative_to(root))


if __name__ == '__main__':
    main(pathlib.Path(sys.argv[1]))
